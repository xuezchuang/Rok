"""Location of the generated runtime data, and the names generated JSON uses for it.

Generators write runtime data (catalogs, config tables, glyph packages, textures) to
Content/RokData, which is staged as UFS and read in C++ through RokDataPaths.
Generated JSON and the provenance that C++ loaders pin by SHA-256 still name those
files by their pre-move "Saved/RokUnityMigration/..." paths. Use label() instead of
path.relative_to(ROOT).as_posix() so regenerated bytes keep matching those pins, and
resolve() to open a file named that way.
Verify reports and Unity evidence stay in Saved/RokUnityMigration.
"""
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_ROOT = PROJECT_ROOT / "Content" / "RokData"

# (pre-move project-relative prefix, prefix under DATA_ROOT); mirrors RokDataPaths.cpp.
LEGACY_PREFIXES = (
    ("Saved/PendingUnityTileRippleRendererV8/", "TileRippleRendererV8/"),
    ("Saved/PendingUnityTileRippleSimulationV2/", "TileRippleSimulationV2/"),
    ("Saved/RokUnityMigration/", ""),
)


def label(path):
    """Project-relative POSIX name for provenance; files under DATA_ROOT keep their pre-move name."""
    path = Path(path)
    try:
        relative = path.relative_to(DATA_ROOT).as_posix()
    except ValueError:
        return path.relative_to(PROJECT_ROOT).as_posix()
    for legacy, data in LEGACY_PREFIXES:
        if relative.startswith(data):
            return legacy + relative[len(data):]
    raise AssertionError(relative)


def resolve(project_relative):
    """Absolute path for a project-relative name; pre-move names resolve to the moved file
    under DATA_ROOT when it exists (mirrors RokDataPaths::ResolveProjectPath)."""
    project_relative = str(project_relative).replace(chr(92), "/")
    for legacy, data in LEGACY_PREFIXES:
        if project_relative.startswith(legacy):
            moved = DATA_ROOT / (data + project_relative[len(legacy):])
            if moved.is_file():
                return moved
            break
    return PROJECT_ROOT / project_relative
