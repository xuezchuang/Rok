"""Generate the runtime lookup from verified Unity sources and UE import receipts."""
import argparse
import csv
import json
import re
from collections import Counter
from pathlib import Path

from BuildRokAcademyVisualSource import yaml_objects
from BuildRokCityBuildingVisualSources import CITY_LAYOUT_TYPES, OUT, ROOT
from BuildRokCityResourceBuildingVisualSources import MODEL_CATALOG
from rok_data_paths import resolve


def vector(values):
    return "FVector(" + ", ".join(f"{x:.10g}" for x in values) + ")"


def nested_warehouse_body(row, base):
    """Unity replaces the prefab root pose at runtime. The body has no overrides."""
    path = resolve(row["scene_prefab"])
    base_prefab = base["prefab"]
    root = next(node for node in base_prefab["nodes"]
                if node["file_id"] == base_prefab["root_game_object_file_id"])
    objects = yaml_objects(path)
    instance, = (body for kind, _, body in objects if kind == 1001)
    if any(kind not in (1, 4, 1001) for kind, _, _ in objects):
        raise ValueError(f"Unexpected visual component in {path}")
    guid = base_prefab["guid"]
    assert re.search(rf"m_SourcePrefab: {{fileID: 100100000, guid: {guid}, type: 3}}", instance)
    assert "m_TransformParent: {fileID: 0}" in instance and "m_RemovedComponents: []" in instance
    allowed = {(root["file_id"], "m_Name")}
    allowed.update((root["transform"]["file_id"], f"{field}.{axis}")
                   for field, axes in (("m_LocalPosition", "xyz"), ("m_LocalRotation", "xyzw"),
                                       ("m_LocalEulerAnglesHint", "xyz")) for axis in axes)
    allowed.add((root["transform"]["file_id"], "m_RootOrder"))
    for node in base_prefab["nodes"]:
        if node["name"] in ("titleto", "empty"):
            allowed.update(((node["file_id"], "m_Name"), (node["transform"]["file_id"], "m_RootOrder")))
    overrides = re.findall(r"- target: {fileID: (\d+), guid: (\w+),\s*type: 3}\s+propertyPath: ([\w.]+)", instance)
    assert len(overrides) == instance.count("propertyPath:")
    assert all(source == guid and (int(target), field) in allowed for target, source, field in overrides)
    return {**base, "matching_model_keys": [row]}


def generate(reports, coverage):
    catalog = json.loads(OUT.read_text(encoding="utf-8"))
    config = json.loads(MODEL_CATALOG.read_text(encoding="utf-8"))
    models = {item["model_id"]: item for item in catalog["models"]}
    alias, base = "build_15_501_3", "build_15_501_2"
    warehouse, = (row for row in config["models"] if row["model_id"] == alias)
    if alias not in models:
        models[alias] = nested_warehouse_body(warehouse, models[base])
    asset_model = {alias: base}
    source = ROOT / "Source/Rok/RokLocalConstructionVisualFactory.cpp"
    existing = {(int(kind), model) for kind, model in re.findall(
        r'\{(\d+), TEXT\("(build_[\d_]+)"\)', source.read_text(encoding="utf-8"))}
    receipts = {}
    for path in reports:
        report = json.loads(path.read_text(encoding="utf-8"))
        assert report["schema"] == "rok.city_building_presentation_assets.ue_create.v1"
        for row in report["models"]:
            receipts[row["model"]] = row
    lines = ["// Generated by Scripts/BuildRokCityBuildingVisualRegistry.py."]
    gaps = []
    registered = set(existing)
    for model, data in sorted(models.items()):
        needed = sorted({key["type"] for key in data["matching_model_keys"]} -
                        {kind for kind, name in existing if name == model})
        if not needed:
            continue
        receipt = receipts.get(asset_model.get(model, model))
        if receipt is None:
            gaps.append(model)
            continue
        nodes = data["prefab"]["nodes"]
        child = next(node for node in nodes if node["file_id"] == data["prefab"]["main_sprite_game_object_file_id"])
        transform = child["transform"]
        rotation = transform["local_rotation"]
        assert all(abs(rotation[axis] - expected) < 1e-6 for axis, expected in
                   zip("xyzw", (0.35355338, 0.35355338, -0.1464466, 0.8535535))), model
        assert not child["renderer"]["flip_x"] and not child["renderer"]["flip_y"], model
        position = vector(transform["local_position"][axis] for axis in "xyz")
        x, y, z = (transform["local_scale"][axis] for axis in "xyz")
        topology = receipt["mesh_topology"]
        bounds = ", ".join(vector(topology[f"bounds_{side}_cm"]) for side in ("min", "max"))
        paths = [receipt["assets"][role] for role in ("mesh", "material")]
        for kind in needed:
            registered.add((kind, model))
            lines.append(f'\t{{{kind}, TEXT("{model}"),')
            for path in paths:
                lines.append(f'\t\tTEXT("{path}.{path.rsplit("/", 1)[-1]}"),')
            lines.append(f"\t\t{position}, {x:.10g}, {topology['vertex_count_lod0']}, "
                         f"{topology['triangle_count_lod0']}, {bounds}, false, false, nullptr, {y:.10g}, {z:.10g}}},")
    output = source.with_name("RokCityBuildingVisuals.generated.inl")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{output}: {(len(lines) - 1) // 4} model/type entries")
    if gaps:
        raise ValueError(f"Missing verified UE import receipts: {', '.join(gaps)}")
    if coverage:
        coverage.parent.mkdir(parents=True, exist_ok=True)
        counts = Counter()
        with coverage.open("w", encoding="utf-8-sig", newline="") as stream:
            columns = ["civilization", "age", "type", "model_id", "status", "scene_prefab", "inherited_body"]
            writer = csv.DictWriter(stream, fieldnames=columns)
            writer.writeheader()
            for row in sorted(config["models"], key=lambda item: (item["civilization"], item["age"], item["type"])):
                model, kind = row["model_id"], row["type"]
                if not row["scene_prefab"]:
                    status = "missing_unity_prefab"
                elif kind in CITY_LAYOUT_TYPES:
                    status = "composite_city_layout"
                elif (kind, model) in registered:
                    status = "connected"
                else:
                    status = "unconnected"
                counts["layout" if kind in CITY_LAYOUT_TYPES else "hall" if kind == 1 else "menu", status] += 1
                writer.writerow({**{key: row[key] for key in columns[:4]}, "status": status,
                                 "scene_prefab": row["scene_prefab"], "inherited_body": asset_model.get(model, "")})
        print(dict(sorted(counts.items())))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reports", type=Path, nargs="+")
    parser.add_argument("--coverage", type=Path)
    args = parser.parse_args()
    generate(args.reports, args.coverage)
