"""Extract city HUD anchors and UpgradeBoard corners from Unity; no editor/build needed."""
import hashlib
import json
import math
import shutil
from pathlib import Path

from PIL import Image
from BuildRokCityBuildingVisualSources import prefab_nodes

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "ref/client-unity/Assets/BundleAssets"
OUT = ROOT / "Content/RokData/CityStatusIndicators"


def rotate(q, v):
    u = [q[k] for k in "xyz"]
    dot = sum(a * b for a, b in zip(u, v))
    cross = [u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0]]
    return [2*dot*u[i] + (q["w"]**2-sum(a*a for a in u))*v[i] + 2*q["w"]*cross[i] for i in range(3)]


def build():
    OUT.mkdir(parents=True, exist_ok=True)
    sources = {}
    for source, target in ((ASSETS / "UI/UITextureStatic/ui_res_common/city_build_upgrad.png", "upgrade.png"),
                           (ASSETS / "Effect/Textures/shared_effecttextures/image004.png", "idle.png")):
        shutil.copyfile(source, OUT / target)
        sources[source.relative_to(ROOT).as_posix()] = hashlib.sha256(source.read_bytes()).hexdigest()
    models = []
    skipped = []
    for path in sorted((ASSETS / "Scene/City_building").rglob("*.prefab")):
        if "UpgradeBoard" not in path.read_text(encoding="utf-8-sig"):
            continue
        try:
            nodes = prefab_nodes(path)
            board = next(n for n in nodes if n["name"] == "UpgradeBoard")
            collider = next(n for n in nodes if n["name"] == "Collider")
            root = next(n for n in nodes if n["transform"]["parent_transform_file_id"] == 0)
            # Other hierarchies need their own transform chain, never guessed anchors.
            assert board["transform"]["parent_transform_file_id"] == root["transform"]["file_id"]
            assert collider["transform"]["parent_transform_file_id"] == root["transform"]["file_id"]
            assert board["renderer"]["sprite_guid"] == "03cb342831f59b14e843307de35f0eef"
        except (AssertionError, StopIteration, KeyError):
            skipped.append(path.relative_to(ROOT).as_posix())
            continue
        transform = board["transform"]
        corners = []
        # city_build_upgrad.png is a 100x100 sprite, pivot (.5,.5), 100 pixels/unit.
        with Image.open(OUT / "upgrade.png") as image:
            assert image.size == (100, 100)
        for x, y in ((-.5, .5), (.5, .5), (-.5, -.5), (.5, -.5)):
            pos = rotate(transform["local_rotation"], [x*transform["local_scale"]["x"], y*transform["local_scale"]["y"], 0])
            pos = [pos[i]+transform["local_position"][k] for i, k in enumerate("xyz")]
            corners.append([pos[0], pos[2], pos[1]])
        tip = collider["transform"]["local_position"]
        models.append({"model": path.stem, "tip": [tip["x"], tip["z"], tip["y"]], "corners": corners})
        sources[path.relative_to(ROOT).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    assert models
    manifest = {"schema": "rok.city_status_indicators.v1", "sources": sources, "models": models, "unsupported_prefabs": skipped}
    (OUT / "sources.json").write_text(json.dumps(manifest, indent=2)+"\n", encoding="utf-8")
    def vec(v):
        assert all(math.isfinite(n) for n in v)
        return "FVector("+", ".join(format(n, ".10g") for n in v)+")"
    lines = ["// Generated by Scripts/BuildRokCityStatusIndicatorSources.py; Unity X,Z,Y local coordinates."]
    for row in models:
        lines.append('{ TEXT("'+row["model"]+'"), '+vec(row["tip"])+", {"+", ".join(vec(v) for v in row["corners"])+"} },")
    (ROOT / "Source/Rok/RokCityStatusIndicatorSources.generated.inl").write_text("\n".join(lines)+"\n", encoding="utf-8")
    print(f"City status sources: {len(models)} models, {len(skipped)} unsupported prefab hierarchies.")


if __name__ == "__main__":
    build()
